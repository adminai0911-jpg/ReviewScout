  const contentDir = path.join(process.cwd(), 'src', 'content', 'articles');
  const filePath = path.join(contentDir, `${resolvedParams.slug}.md`);
  
  if (!fs.existsSync(filePath)) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50">
        <div className="text-center">
          <h1 className="text-4xl font-bold text-slate-800 mb-4">Article Not Found</h1>
          <Link href="/" className="text-indigo-600 hover:underline">← Back to Homepage</Link>
        </div>
      </div>
    );
  }

  const fileContent = fs.readFileSync(filePath, 'utf-8');
  const { data, content } = matter(fileContent);

  // CRO: Extract the Amazon Link from the markdown for the sticky mobile button
  const amazonLinkMatch = content.match(/\[.*\]\((https:\/\/amazon\.com\/dp\/[^)]+)\)/);
