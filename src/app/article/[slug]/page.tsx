  const relatedFiles = shuffled.slice(0, 3);
  const relatedArticles = relatedFiles.map(f => {
    const fc = fs.readFileSync(path.join(contentDir, f), 'utf-8');
    const fData = matter(fc).data;
    return { slug: f.replace('.md', ''), title: fData.title };
  });

